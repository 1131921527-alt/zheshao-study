"""wordEmoji v2 改造（最终版）：
1. 现有规则删掉中文关键词段（中文子串误命中灾难：相信→信、宣布→布、输入→输、飞船→船、星期→星）
2. 保留英文 \\b 匹配部分，去重
3. 末尾插入 CN_RULES：只写干净的关键词枚举（危险单字一律用多字词，仅保留语义域唯一的安全单字）
4. 默认 🎟 → 📝
"""
import re, sys

SRC = 'study.html'
html = open(SRC, encoding='utf-8').read()

m = re.search(r"(function wordEmoji\(word, cn\)\{.*?var map=\[)(.*?)(\];\s*\n\s*for\(var i=0;i<map\.length)", html, re.S)
if not m:
    print('FATAL: map region not found'); sys.exit(1)

rules = re.findall(r"\[/((?:.|\n)*?)/,\s*'(.+?)'\]", m.group(2))
print('original rules:', len(rules))

def strip_cn(pat):
    parts = pat.split('|')
    keep = [p for p in parts if p and not any('\u4e00' <= c <= '\u9fff' for c in p)]
    return '|'.join(keep)

new_rules, seen = [], set()
for pat, emoji in rules:
    p2 = strip_cn(pat).strip()
    if not p2:
        continue
    if p2 == r'\b(road|street|path|highway|route|journey|trip|travel|tour|tourism)\b':
        p2 = r'\b(road|street|path|highway|route)\b'  # travel 系列留给旅行规则🧭
    key = (p2, emoji)
    if key in seen:
        continue
    seen.add(key)
    new_rules.append((p2, emoji))
print('after strip+dedup:', len(new_rules))

