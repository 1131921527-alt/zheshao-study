def strip_cn(pat):
    keep = [p for p in pat.split('|')
            if p and not any('\u4e00' <= c <= '\u9fff' for c in p)]
    return '|'.join(keep).strip()

new_rules, seen = [], set()
for pat, emoji in rules:
    p2 = strip_cn(pat)
    if not p2:
        continue
    key = (p2, emoji)
    if key in seen:
        continue
    seen.add(key)
    new_rules.append((p2, emoji))
print('after strip+dedup:', len(new_rules))

