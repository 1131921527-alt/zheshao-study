<p>关键点：<strong>短期股价波动≠公司价值变化</strong>。一家好公司可能因为市场情绪不好而股价大跌（错杀），一家烂公司也可能因为炒作而股价大涨（泡沫）。所以炒股本质上是两种玩法：<strong>投资</strong>（基于公司内在价值做决策）和<strong>投机</strong>（基于价格波动做决策）。新手建议走投资路线。</p>

